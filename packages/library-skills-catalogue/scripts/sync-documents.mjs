import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const documentsRoot = resolve(packageRoot, "src/documents");
const outputPath = resolve(packageRoot, "src/generated/documents.ts");

async function listFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const fullPath = resolve(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await listFiles(fullPath)));
    } else if (entry.isFile()) {
      files.push(fullPath);
    }
  }

  return files;
}

function toPosixPath(value) {
  return value.split(sep).join("/");
}

const skillDirectories = (await readdir(documentsRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right));

const skills = [];

for (const directory of skillDirectories) {
  const files = await listFiles(resolve(documentsRoot, directory));
  const skillFile = files.find(
    (file) => toPosixPath(relative(resolve(documentsRoot, directory), file)) === "SKILL.md",
  );

  if (!skillFile) {
    throw new Error(`Skill directory ${directory} has no SKILL.md`);
  }

  const resources = [];

  for (const file of files) {
    if (file === skillFile) {
      continue;
    }

    resources.push({
      path: toPosixPath(relative(resolve(documentsRoot, directory), file)),
      content: await readFile(file, "utf8"),
    });
  }

  skills.push({
    directory,
    rawContent: await readFile(skillFile, "utf8"),
    resources,
  });
}

const source = `import type { SkillDocumentSource } from "../types.js";

// Generated by scripts/sync-documents.mjs from src/documents. Do not edit by hand.
export const builtInSkillDocumentSources = ${JSON.stringify(skills, null, 2)} as const satisfies readonly SkillDocumentSource[];
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source);
console.log(`Wrote ${skills.length} skill documents to ${relative(packageRoot, outputPath)}`);
