import { readdir, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIRECTORY = dirname(fileURLToPath(import.meta.url));
const SKILLS_DIRECTORY = resolve(SCRIPT_DIRECTORY, "../src/data-model/skills");
const OUTPUT_PATH = join(SKILLS_DIRECTORY, "index.ts");
const RESOURCE_ROOTS = ["references", "scripts", "assets"];

async function listFiles(directory, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;

    if (entry.isDirectory()) {
      files.push(...(await listFiles(join(directory, entry.name), path)));
      continue;
    }

    files.push(path);
  }

  return files;
}

function toIdentifier(skill, path) {
  const segments = [skill, ...(path ? path.replace(/\.[^.]+$/, "").split("/") : [])];

  return segments
    .flatMap((segment) => segment.split("-"))
    .map((segment, index) =>
      index === 0 ? segment : `${segment.charAt(0).toUpperCase()}${segment.slice(1)}`,
    )
    .join("");
}

async function readSkillDirectories() {
  const entries = await readdir(SKILLS_DIRECTORY, { withFileTypes: true });
  const skills = [];

  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    if (!entry.isDirectory()) {
      continue;
    }

    const directory = join(SKILLS_DIRECTORY, entry.name);

    await stat(join(directory, "SKILL.md"));

    const resources = (await listFiles(directory))
      .filter((path) => path !== "SKILL.md")
      .filter((path) => RESOURCE_ROOTS.includes(path.split("/")[0]));

    skills.push({ name: entry.name, resources });
  }

  return skills;
}

export function renderSkillIndex(skills) {
  const imports = skills
    .flatMap((skill) => [
      ...skill.resources.map((path) => ({
        specifier: `./${skill.name}/${path}`,
        identifier: toIdentifier(skill.name, path),
      })),
      { specifier: `./${skill.name}/SKILL.md`, identifier: toIdentifier(skill.name) },
    ])
    // Match the formatter's case-insensitive specifier ordering so the committed file is stable.
    .sort((left, right) =>
      left.specifier.toLowerCase().localeCompare(right.specifier.toLowerCase()),
    )
    .map((entry) => `import ${entry.identifier} from "${entry.specifier}";`);

  const entries = skills.map((skill) => {
    const resources = skill.resources
      .map((path) => `      { path: "${path}", content: ${toIdentifier(skill.name, path)} },`)
      .join("\n");

    return [
      "  {",
      `    directory: "${skill.name}",`,
      `    rawContent: ${toIdentifier(skill.name)},`,
      skill.resources.length > 0 ? `    resources: [\n${resources}\n    ],` : "    resources: [],",
      "  },",
    ].join("\n");
  });

  return [
    "// Generated by scripts/generate-skill-index.mjs. Do not edit by hand.",
    "",
    ...imports,
    "",
    "export const builtInSkillDocuments = [",
    ...entries,
    "] as const;",
    "",
  ].join("\n");
}

export async function buildSkillIndex() {
  return renderSkillIndex(await readSkillDirectories());
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(OUTPUT_PATH, await buildSkillIndex(), "utf8");
  console.log(`Wrote ${OUTPUT_PATH}`);
}
